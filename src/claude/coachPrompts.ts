export function buildSnapshotBlock(snapshot: CoachSnapshot): string {
  return `Данные пользователя (JSON):\n${JSON.stringify(snapshot)}`;
}

export function buildContextBlock(context: string): string {
  return `Разговор начат из сообщения бота, которое видел пользователь:\n${context}`;
}

export function buildCommentRequest(
  kind: PeriodKind,
  snapshot: CoachSnapshot,
  summaries: DaySummary[],
): string {
  const period = kind === "day" ? "итогам сегодняшнего дня" : "итогам этой недели (пн–вс)";
  return [
    `Напиши комментарий к ${period}.`,
    "",
    buildSnapshotBlock(snapshot),
    "",
    `Дни отчёта (JSON):\n${JSON.stringify(summaries)}`,
  ].join("\n");
}

